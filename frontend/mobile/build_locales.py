# Parse embedded dictionary blocks from i18n.ts for languages that were in i18n.ts
with open('services/i18n.ts', 'r', encoding='utf-8') as f:
    i18n_code = f.read()

def parse_embedded_lang_dict(code: str) -> dict:
    match = re.search(r'\n  ' + code + r':\s*\{([\s\S]*?)\n  \},', i18n_code)
    if not match:
        return {}
    block = match.group(1)
    res = {}
    for line in block.splitlines():
        line = line.strip()
        m = re.match(r'^([a-zA-Z0-9_]+):\s*[\'"`](.*)[\'"`],?$', line)
        if m:
            res[m.group(1)] = m.group(2).replace("\\'", "'")
    return res

embedded_codes = ['hi', 'ml', 'ta', 'te', 'kn', 'bn', 'mr', 'gu', 'pa', 'or', 'as']
for c in embedded_codes:
    parsed = parse_embedded_lang_dict(c)
    if c not in existing_jsons or not existing_jsons[c]:
        existing_jsons[c] = parsed
    else:
        # Merge parsed
        for k, v in parsed.items():
            if k not in existing_jsons[c]:
                existing_jsons[c][k] = v

