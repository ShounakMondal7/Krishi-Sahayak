# Fallbacks for other scheduled languages (brx, doi, kok, ks, mni, sat, sd)
# Default to Hindi or English based Indic terms if missing
GENERIC_INDIC_FALLBACK = TRANSLATIONS_MAP["hi"]

def main():
    files = [f for f in os.listdir(LOCALES_DIR) if f.endswith(".json")]
    print(f"Found {len(files)} locale JSON files in {LOCALES_DIR}")
    
    for filename in sorted(files):
        lang = filename.split(".")[0]
        filepath = os.path.join(LOCALES_DIR, filename)
        
        with open(filepath, "r", encoding="utf-8") as f:
            data = json.load(f)
            
        trans_dict = TRANSLATIONS_MAP.get(lang, GENERIC_INDIC_FALLBACK)
        updated_count = 0
        
        for k, v in trans_dict.items():
            if k not in data or data[k] != v:
                data[k] = v
                updated_count += 1
                
        # Also ensure common labels like backBtn, whereIsYourFarmTitle, etc. are properly set
        if "backBtn" not in data:
            data["backBtn"] = "वापस" if lang in ["hi", "mr", "mai", "ne", "sa"] else "Back"
            updated_count += 1
            
        with open(filepath, "w", encoding="utf-8") as f:
            json.dump(data, f, ensure_ascii=False, indent=2)
            
        print(f"Updated {filename} with {updated_count} key updates/additions.")

if __name__ == "__main__":
    main()
